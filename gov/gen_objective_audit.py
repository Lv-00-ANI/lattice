def render():
    L = []
    L.append("# 目标原文逐句对照：哪些是定理、哪些是检查、哪些是定位声明")
    L.append("")
    L.append("**本文件由 `gov/gen_objective_audit.py` 生成，勿手改。**")
    L.append("")
    L.append("目标是一段话。`OBJECTIVE-MAP.md` 按 14 个条款列出载体；本文件按**原句**列出")
    L.append("**每一句的性质**——这比载体清单更重要，因为**有些句子不是数学命题**。")
    L.append("")
    L.append("## 为什么要分三类")
    L.append("")
    L.append("把「所有 LLM 都可落在这条链路上」写成 Lean 定理会是**假的**：它是关于外部世界的")
    L.append("声明，不是关于本库结构的声明。**一份诚实的审计必须说清哪句是定理、哪句是检查、")
    L.append("哪句是定位**——否则「目标达成」就成了自我评价。")
    L.append("")
    L.append("| 类别 | 含义 |")
    L.append("|:--|:--|")
    L.append("| **定理** | 有 Lean 声明，内核检查过 |")
    L.append("| **检查** | 有 `gov/` 脚本强制执行，能失败 |")
    L.append("| **定位声明** | 关于外部世界的判断；本库提供其**可验证的部分**，并明说其余不可形式化 |")
    L.append("")
    L.append("## 逐句")
    L.append("")
    L.append("| 目标原句 | 类别 | 证据 | 备注 |")
    L.append("|:--|:--|:--|:--|")
    counts = {}
    # The theorem count is MEASURED, not written down: this document used to say 8,279 while the
    # tree had 8,296, because the number was a literal in SENTENCES. A generated file that carries a
    # hand-copied count is the same defect the census documents had.
    from audit_counts import total_theorems
    theorems = "{:,}".format(total_theorems())
    for sentence, kind, evidence, note in SENTENCES:
        counts[kind] = counts.get(kind, 0) + 1
        evidence = evidence.replace("{theorems}", theorems)
        L.append("| %s | **%s** | %s | %s |" % (sentence, kind, evidence, note or ""))
    L.append("")
    L.append("## 汇总")
    L.append("")
    for k in ["theorem", "check", "positioning"]:
        L.append("- %s：%d 句" % (k, counts.get(k, 0)))
    L.append("")
    L.append("**「彻底做完」的含义因此是明确的**：")
    L.append("")
    L.append("- 所有**定理**句都有 Lean 载体，且 `gate.py` 保证无 axiom / 无 sorry；")
    L.append("- 所有**检查**句都有能失败的脚本；")
    L.append("- 所有**定位**句的可验证部分都有守卫，**不可形式化的部分被明说，而不是被含糊过去**。")
    L.append("")
    L.append("**没有任何一句是被跳过的。**")
    return "\n".join(L) + "\n"


def self_test():
    """**A guard that cannot fail is not a guard.**

    Two directions:
      1. the REAL citation set must pass (otherwise the table is broken);
      2. a FABRICATED phantom citation must be caught (otherwise the check is vacuous).
    """
    ok = True

    have = declared_names()
    real = cited_names()
    if not real:
        print("  self-test FAILED: no citations were extracted -- the regex is not reading them")
        return False
    print("  real citations        : %d, all declared: %s"
          % (len(real), sorted(real - have) == []))
    if real - have:
        print("  real citations missing: " + ", ".join(sorted(real - have)))
        ok = False

    # a name that is deliberately not in the tree
    phantom = "thisDeclarationDoesNotExist_966"
    if phantom in have:
        print("  self-test FAILED: the phantom is somehow declared")
        return False
    detected = sorted((real | {phantom}) - have)
    if detected != [phantom]:
        print("  self-test FAILED: the phantom was NOT detected (got %r)" % (detected,))
        ok = False
    else:
        print("  phantom detected      : %s" % phantom)
    return ok


def main(argv):
    if "--self-test" in argv:
        ok = self_test()
        print("  self-test: %s" % ("PASS" if ok else "FAIL"))
        return 0 if ok else 1
    if not check_citations():
        return 1
    text = render()
    if "--check" in argv:
        if not os.path.exists(OUT):
            print("OBJECTIVE-AUDIT: missing")
            return 1
        if io.open(OUT, encoding="utf-8").read() != text:
            print("OBJECTIVE-AUDIT: STALE -- regenerate with gov/gen_objective_audit.py")
            return 1
        print("OBJECTIVE-AUDIT: up to date")
        return 0
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
