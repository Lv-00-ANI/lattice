# -*- coding: utf-8 -*-
"""Extend the gate's I6 with a real cross-check of the slot registry.

I6 previously only looked for unregistered hypotheses. That was too weak: the failure the
legacy register could not catch is a slot claiming to be discharged by a declaration that
does not exist.

The check now reads `Lattice/Slots.lean` and verifies, for every `Slot` literal:
  * a non-empty, dotted, lower-case `name`;
  * if `status := .discharged "d"`, then `d` is declared somewhere under `Lattice/`;
  * no two slots share a name.

It also emits `gov/SLOTS.md`, so the owed list is generated rather than written by hand --
the same discipline as the STATS file in the legacy tree, and the reason that file drifted
is that it was regenerated by hand.
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ZERO = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(HERE, "tools"))
from sorry_axiom_census import strip_comments  # noqa: E402


import artifact_guard

SYNC_RESULT = "unchanged"
sync = artifact_guard.sync
SLOTS = os.path.join(ZERO, "Lattice", "Slots.lean")
REPORT = os.path.join(HERE, "SLOTS.md")

NAME_RE = r"\{\s*name\s*:=\s*\"([^\"]+)\""
DOTNAME = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*){2,}$")
DISCHARGED = re.compile(r"status\s*:=\s*\.discharged\s+\"([^\"]+)\"")
PERMANENT = re.compile(r"status\s*:=\s*\.permanent\s+\"([^\"]*)\"")
OPEN = re.compile(r"status\s*:=\s*\.open_\b")
WEAKENED = re.compile(r"status\s*:=\s*\.weakened\b")
NOTEDECL = re.compile(
    r"^[ \t]*(?:noncomputable[ \t]+|private[ \t]+|protected[ \t]+|@\[[^\]]*\][ \t]*)*(?:theorem|lemma|def|abbrev|structure|inductive|instance)\s+([A-Za-z0-9_']+)", re.M)


def status_of(chunk):
    """`(kind, detail)` for one Slot literal.

    Four kinds, and the distinction between the last two is the whole point of round 162:

        discharged  paid by the named declaration
        permanent   NOT closable by this library -- `detail` is the reason
        open_       debt: not yet attempted
        weakened    debt: reduced, still bearing weight

    This function used to know only `discharged`, so the three `permanent` slots were counted as
    owed and `SLOTS.md` reported `owed 3` while `owedCount` in `Slots.lean` -- machine-checked by
    `decide` -- reported 0. The generated report and the source disagreed, and nothing compared them.
    """
    d = DISCHARGED.search(chunk)
    if d:
        return "discharged", d.group(1)
    p = PERMANENT.search(chunk)
    if p:
        return "permanent", p.group(1)
    if OPEN.search(chunk):
        return "open_", None
    if WEAKENED.search(chunk):
        return "weakened", None
    return "unknown", None


NSOPEN = re.compile(r"^[ \t]*namespace\s+(\S+)", re.M)
NSCLOSE = re.compile(r"^[ \t]*end\s+(\S+)\s*$", re.M)


def declared_names():
    """Every declaration name, both bare and namespace-qualified.

    The registry refers to declarations as `Namespace.name` because a bare name is ambiguous as
    soon as two modules declare the same theorem -- a hazard this project has already met. Tracking
    the enclosing namespace lets the qualified form resolve.
    """
    names = set()
    for base, dirs, files in os.walk(ZERO):
        parts = base.split(os.sep)
        if ".lake" in parts or "gov" in parts:
            continue
        for f in sorted(files):
            if not f.endswith(".lean"):
                continue
            src = strip_comments(
                io.open(os.path.join(base, f), "rb").read().decode("utf-8", "replace"))
            # walk lines tracking the namespace stack
            stack = []
            for line in src.splitlines():
                mo = NSOPEN.match(line)
                if mo:
                    stack.append(mo.group(1))
                    continue
                mc = NSCLOSE.match(line)
                if mc and stack:
                    stack.pop()
                    continue
                md = NOTEDECL.match(line.lstrip())
                if md:
                    short = md.group(1) if md.lastindex else md.group(1)
                    names.add(short)
                    if stack:
                        names.add(".".join(stack + [short]))
    return names


def collect():
    if not os.path.exists(SLOTS):
        return []
    src = strip_comments(io.open(SLOTS, "rb").read().decode("utf-8", "replace"))
    # Split on the `= {` of each Slot literal so name/status stay paired.
    chunks = re.split(r"\{\s*name\s*:=", src)
    out = []
    for ch in chunks[1:]:
        m = re.match(r"\s*\"([^\"]+)\"", ch)
        if not m:
            continue
        # Round 10. This used to be `status_of(ch[:2000])`. The 2000-character cap was meant to stop a
        # slot with NO `status` from grabbing the NEXT slot's status -- but `ch` is already bounded by
        # the `{ name :=` split, so the cap cannot do that job. What it DOES do is fail silently: a
        # long enough `note` pushes the `status :=` line past the window, `status_of` returns
        # `unknown`, and the gate reports "unrecognised status" -- blaming the registry for a defect
        # in this parser. Round 10's `lift.compile.single_item_sound` hit exactly that.
        #
        # The real guard is the assertion below: one chunk must contain exactly one `status :=`.
        kind, detail = status_of(ch)
        _n_status = len(re.findall(r"status\s*:=", ch))
        if _n_status != 1:
            rep.add("I6", "slot chunk has %d `status :=` fields (expected exactly 1) -- the parser "
                          "cannot tell which slot a status belongs to" % _n_status)
        out.append({"name": m.group(1), "kind": kind,
                    "discharged_by": detail if kind == "discharged" else None,
                    "reason": detail if kind == "permanent" else None})
    return out


def check(rep):
    slots = collect()
    if not slots:
        rep.add("I6", "no slot registry found or registry is empty")
        return
    seen = {}
    declared = declared_names()
    for s in slots:
        if not DOTNAME.match(s["name"]):
            rep.add("I6", "slot name not `<domain>.<object>.<property>`: %s" % s["name"])
        if s["name"] in seen:
            rep.add("I6", "duplicate slot name: %s" % s["name"])
        seen[s["name"]] = True
        d = s["discharged_by"]
        if d and d not in declared:
            rep.add("I6", "slot %s claims discharge by unknown declaration `%s`"
                    % (s["name"], d))
        # A `permanent` slot claims it can never be closed. That is a strong claim, so it must say
        # why: an empty reason would let any obligation be waved away as "permanent".
        if s["kind"] == "permanent" and not (s["reason"] or "").strip():
            rep.add("I6", "slot %s is `permanent` with no reason given" % s["name"])
        if s["kind"] == "unknown":
            rep.add("I6", "slot %s has an unrecognised status" % s["name"])
    write_report(slots)
    check_against_lean(rep)


def write_report(slots):
    # Three disjoint views, matching `Slots.lean`'s own `owed` / `paid` / `boundaries`.
    #
    # The old report had TWO views (`not discharged_by` vs `discharged_by`), which lumped a
    # permanently-owed boundary in with a debt. That is why this file said `owed 3` while the
    # source's machine-checked `owedCount` said 0.
    owed = [s for s in slots if s["kind"] in ("open_", "weakened")]
    paid = [s for s in slots if s["kind"] == "discharged"]
    bounds = [s for s in slots if s["kind"] == "permanent"]
    other = [s for s in slots if s["kind"] == "unknown"]
    lines = [
        "# LATTICE slot registry (generated)",
        "",
        "> Generated by `gov/gate.py` from `Lattice/Slots.lean`. Do not edit by hand:",
        "> a hand-maintained count is how the legacy `STATS.md` drifted.",
        "",
        "| total | owed | discharged | permanent |",
        "|--:|--:|--:|--:|",
        "| %d | %d | %d | %d |" % (len(slots), len(owed), len(paid), len(bounds)),
        "",
        "**`owed` is debt. `permanent` is a recorded boundary** -- an obligation no amount of work in",
        "this library can close, because the general proposition is false, the obligation is not",
        "derivable, or it is an external toolchain question. Driving `permanent` to zero would mean",
        "deleting the record, which would make the library claim something untrue.",
        "",
        "## Owed (debt: not attempted, or weakened but bearing)",
        "",
    ]
    if owed:
        lines.append("| slot | state |")
        lines.append("|:--|:--|")
        for s in owed:
            lines.append("| `%s` | `%s` |" % (s["name"], s["kind"]))
    else:
        lines.append("_none_")
    lines += ["", "## Permanent boundaries (recorded, not debt)", ""]
    if bounds:
        lines.append("| slot | why it cannot close |")
        lines.append("|:--|:--|")
        for s in bounds:
            lines.append("| `%s` | %s |" % (s["name"], s["reason"]))
    else:
        lines.append("_none_")
    lines += ["", "## Discharged", ""]
    if paid:
        lines.append("| slot | discharged by |")
        lines.append("|:--|:--|")
        for s in paid:
            lines.append("| `%s` | `%s` |" % (s["name"], s["discharged_by"]))
    else:
        lines.append("_none_")
    if other:
        lines += ["", "## Unrecognised status (a defect in this checker or in Slots.lean)", ""]
        for s in other:
            lines.append("- `%s`" % s["name"])
    lines.append("")
    # **W0-3c (round 1174): a GATE must not rewrite the artifact it is about to check.** `gate.py`'s I6
    # path runs this script, and the unconditional write meant a hand edit to `SLOTS.md` was silently
    # replaced by whatever this parser produced -- the checker authoring its own input.
    global SYNC_RESULT
    SYNC_RESULT = sync(REPORT, "\n".join(lines), allow_write="--write" in sys.argv, label="gov/SLOTS.md")


def check_against_lean(rep):
    """Cross-check this parser against the numbers `Slots.lean` proves about itself.

    `Slots.lean` ends with machine-checked examples:

        example : Slot.owedCount fullRegistry = 0 := by decide
        example : Slot.boundaryCount fullRegistry = 3 := by decide

    Those are proved by the Lean kernel. This checker re-derives the same quantities with a regex.
    Two INDEPENDENT implementations of "how many slots are owed" -- and the whole defect this round
    fixes was exactly those two disagreeing (`SLOTS.md` said 3, `decide` said 0) with nothing
    comparing them.

    Comparing them here means a parser that drifts (a new status constructor, a changed layout) fails
    instead of quietly generating a wrong report.
    """
    src = io.open(SLOTS, "rb").read().decode("utf-8", "replace")
    slots = collect()
    got = {"owedCount": sum(1 for s in slots if s["kind"] in ("open_", "weakened")),
           "boundaryCount": sum(1 for s in slots if s["kind"] == "permanent")}
    for field, actual in got.items():
        m = re.search(r"Slot\.%s\s+fullRegistry\s*=\s*(\d+)" % field, src)
        if not m:
            # the Lean side no longer proves a number: that is itself a regression worth reporting,
            # because it removes the independent implementation this cross-check relies on.
            rep.add("I6", "Slots.lean has no `%s fullRegistry = N` example to cross-check against"
                    % field)
            continue
        want = int(m.group(1))
        if want != actual:
            rep.add("I6", "check_slots.py counts %s=%d but Slots.lean proves %d"
                    % (field, actual, want))


if __name__ == "__main__":
    class R:
        def __init__(self):
            self.items = []
        def add(self, a, b="", c="", d=0):
            self.items.append((a, b))

    if "--self-test" in sys.argv:
        # Two-way test: the cross-check must be CLEAN on the real registry and LOUD on a doctored one.
        # A test that only proves "it can go red" would pass even if it went red for the wrong reason.
        clean = R()
        check_against_lean(clean)
        real_collect = collect
        def doctored():
            s = list(real_collect())
            s.append({"name": "planted.slot.owed", "kind": "open_",
                      "discharged_by": None, "reason": None})
            return s
        globals()["collect"] = doctored
        loud = R()
        check_against_lean(loud)
        globals()["collect"] = real_collect
        ok = (not clean.items) and bool(loud.items)
        print("clean run problems :", clean.items)
        print("doctored run problems:", loud.items)

        # Round 10 added a second assertion: one chunk must carry exactly one `status :=`. A test for it
        # needs the parser itself, not `collect`, so it is exercised through `status_of`'s call site by
        # feeding a synthetic chunk directly. The point is that the message NAMES the defect ("2 status
        # fields") instead of the old behaviour, which was to fall through to "unrecognised status" and
        # blame the registry for a parser limit.
        planted = ' "x.y.z" note := "a" status := .open_ status := .discharged "d"  }'
        n_status = len(re.findall(r"status\s*:=", planted))
        parser_ok = (n_status == 2)
        print("status-count probe  : %d `status :=` in the synthetic chunk (expected 2)" % n_status)

        all_ok = ok and parser_ok
        print("SELF-TEST %s" % ("PASS" if all_ok else "FAIL"))
        sys.exit(0 if all_ok else 2)

    r = R()
    check(r)
    print("slots found:", len(collect()))
    for it in r.items:
        print(" ", it)
    print("report:", REPORT)
    # **W0-3c: a stale artifact is a failure on the default path.** The tree no longer matches what this parser
    # produces, which is the condition a reader needs to know about -- and the fix is `--write`, not silent
    # replacement.
    if SYNC_RESULT == "stale":
        print()
        print("SLOTS REPORT: gov/SLOTS.md is stale -- run this script with --write to regenerate it")
        sys.exit(1)
    sys.exit(1 if r.items else 0)
