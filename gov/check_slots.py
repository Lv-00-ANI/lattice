# -*- coding: utf-8 -*-
"""Extend the gate's I6 with a real cross-check of the slot registry.

I6 previously only looked for unregistered hypotheses. That was too weak: the failure the
legacy register could not catch is a slot claiming to be discharged by a declaration that
does not exist.

The check now reads `Lattice/Slots.lean` and verifies, for every `Slot` literal:
  * a non-empty, dotted, lower-case `name`;
  * if `status := .discharged "d"`, then `d` is declared somewhere under `Lattice/`;
  * no two slots share a name.

It also emits `gov/SLOTS.md`, so the owed list is generated rather than written by hand --
the same discipline as the STATS file in the legacy tree, and the reason that file drifted
is that it was regenerated by hand.
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ZERO = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(HERE, "tools"))
from sorry_axiom_census import strip_comments  # noqa: E402

SLOTS = os.path.join(ZERO, "Lattice", "Slots.lean")
REPORT = os.path.join(HERE, "SLOTS.md")

NAME_RE = r"\{\s*name\s*:=\s*\"([^\"]+)\""
DOTNAME = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*){2,}$")
DISCHARGED = re.compile(r"status\s*:=\s*\.discharged\s+\"([^\"]+)\"")
NOTEDECL = re.compile(
    r"^[ \t]*(?:noncomputable[ \t]+|private[ \t]+|protected[ \t]+|@\[[^\]]*\][ \t]*)*(?:theorem|lemma|def|abbrev|structure|inductive|instance)\s+([A-Za-z0-9_']+)", re.M)


NSOPEN = re.compile(r"^[ \t]*namespace\s+(\S+)", re.M)
NSCLOSE = re.compile(r"^[ \t]*end\s+(\S+)\s*$", re.M)


def declared_names():
    """Every declaration name, both bare and namespace-qualified.

    The registry refers to declarations as `Namespace.name` because a bare name is ambiguous as
    soon as two modules declare the same theorem -- a hazard this project has already met. Tracking
    the enclosing namespace lets the qualified form resolve.
    """
    names = set()
    for base, dirs, files in os.walk(ZERO):
        parts = base.split(os.sep)
        if ".lake" in parts or "gov" in parts:
            continue
        for f in sorted(files):
            if not f.endswith(".lean"):
                continue
            src = strip_comments(
                io.open(os.path.join(base, f), "rb").read().decode("utf-8", "replace"))
            # walk lines tracking the namespace stack
            stack = []
            for line in src.splitlines():
                mo = NSOPEN.match(line)
                if mo:
                    stack.append(mo.group(1))
                    continue
                mc = NSCLOSE.match(line)
                if mc and stack:
                    stack.pop()
                    continue
                md = NOTEDECL.match(line.lstrip())
                if md:
                    short = md.group(1) if md.lastindex else md.group(1)
                    names.add(short)
                    if stack:
                        names.add(".".join(stack + [short]))
    return names


def collect():
    if not os.path.exists(SLOTS):
        return []
    src = strip_comments(io.open(SLOTS, "rb").read().decode("utf-8", "replace"))
    # Split on the `= {` of each Slot literal so name/status stay paired.
    chunks = re.split(r"\{\s*name\s*:=", src)
    out = []
    for ch in chunks[1:]:
        m = re.match(r"\s*\"([^\"]+)\"", ch)
        if not m:
            continue
        d = DISCHARGED.search(ch[:2000])
        out.append({"name": m.group(1), "discharged_by": d.group(1) if d else None})
    return out


def check(rep):
    slots = collect()
    if not slots:
        rep.add("I6", "no slot registry found or registry is empty")
        return
    seen = {}
    declared = declared_names()
    for s in slots:
        if not DOTNAME.match(s["name"]):
            rep.add("I6", "slot name not `<domain>.<object>.<property>`: %s" % s["name"])
        if s["name"] in seen:
            rep.add("I6", "duplicate slot name: %s" % s["name"])
        seen[s["name"]] = True
        d = s["discharged_by"]
        if d and d not in declared:
            rep.add("I6", "slot %s claims discharge by unknown declaration `%s`"
                    % (s["name"], d))
    write_report(slots)


def write_report(slots):
    owed = [s for s in slots if not s["discharged_by"]]
    paid = [s for s in slots if s["discharged_by"]]
    lines = [
        "# LATTICE slot registry (generated)",
        "",
        "> Generated by `gov/gate.py` from `Lattice/Slots.lean`. Do not edit by hand:",
        "> a hand-maintained count is how the legacy `STATS.md` drifted.",
        "",
        "| total | owed | discharged |",
        "|--:|--:|--:|",
        "| %d | %d | %d |" % (len(slots), len(owed), len(paid)),
        "",
        "## Owed (load-bearing, not yet proved)",
        "",
    ]
    if owed:
        lines.append("| slot | discharged by |")
        lines.append("|:--|:--|")
        for s in owed:
            lines.append("| `%s` | — |" % s["name"])
    else:
        lines.append("_none_")
    lines += ["", "## Discharged", ""]
    if paid:
        lines.append("| slot | discharged by |")
        lines.append("|:--|:--|")
        for s in paid:
            lines.append("| `%s` | `%s` |" % (s["name"], s["discharged_by"]))
    else:
        lines.append("_none_")
    lines.append("")
    io.open(REPORT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))


if __name__ == "__main__":
    class R:
        def __init__(self):
            self.items = []
        def add(self, a, b="", c="", d=0):
            self.items.append((a, b))
    r = R()
    check(r)
    print("slots found:", len(collect()))
    for it in r.items:
        print(" ", it)
    print("report:", REPORT)
